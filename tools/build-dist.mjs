#!/usr/bin/env node
// build-dist — the stylesheet, cut into pieces a host can choose from.
//
// The library ships one stylesheet today: `components/um-components.css`,
// 274 KB, every component in it. That is the right answer for a documentation
// site and the wrong answer for a product: a product that uses a button and a
// table is still downloading a carousel, a date picker, a virtual tree and
// their selectors.
//
// Element Plus answers this by shipping `theme-chalk/el-button.css` next to
// `theme-chalk/base.css`, and Arco by shipping one style entry per
// component. So the library does the same:
//
//   css/base.css      the shared layer and the box model — link it once
//   css/<id>.css      one component, with the quality hooks that belong to it
//   css/all.css       the whole sheet, for a host that wants one file
//
// The pieces are cut from the same chunk list the full sheet is assembled
// from, so the two cannot disagree: `css/all.css` and
// `components/um-components.css` are the same stylesheet.
//
// The quality hooks close each component's file rather than sitting in a file
// of their own. A hook is a rule that overrides the component's own shadow —
// `.um-button--glow` beats the shadow `.um-button` gives itself — so it has to
// come after that component's rules, and it has to be present whenever that
// component is. Putting it in a separate file would make "did you remember to
// link hooks.css" a question every host has to answer; putting it in the
// component's own file makes it impossible to forget.

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { assembleChunks } from "./lib/component-chunks.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "css");

const { chunks, manifests, problems } = assembleChunks(root);
if (problems.length) {
  for (const p of problems) console.error(`dist: ${p}`);
  console.log(`dist: FAIL (${problems.length} errors)`);
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });

const shared = chunks.filter(
  (c) => c.kind === "shared" || c.kind === "box-model" || c.kind === "motion",
);
const hooks = chunks.filter((c) => c.kind === "hooks");
const components = chunks.filter((c) => c.kind === "component");

// --- the shared layer --------------------------------------------------------

const baseHeader = [
  `/* ============================================================================`,
  `   ui-moods · shared layer`,
  `   ----------------------------------------------------------------------------`,
  `   GENERATED by tools/build-dist.mjs — do not edit.`,
  `  `,
  `   Link this once, before the components:`,
  `     <link rel="stylesheet" href="css/base.css">`,
  `  `,
  `   It holds the layer constants every component derives from, the one focus`,
  `   treatment and the one disabled treatment, and the box model — which is`,
  `   scoped to the library's own elements, so it changes nothing in the host.`,
  `   ========================================================================== */`,
  ``,
].join("\n");

writeFileSync(
  join(outDir, "base.css"),
  `${baseHeader}${shared.map((c) => c.css).join("\n\n")}\n`,
  "utf8",
);

// --- one file per component --------------------------------------------------

for (const c of components) {
  const header = [
    `/* ============================================================================`,
    `   ui-moods · ${c.title} (${c.id})`,
    `   ----------------------------------------------------------------------------`,
    `   GENERATED by tools/build-dist.mjs — do not edit.`,
    `  `,
    `   Link css/base.css once, then this file, for each component you use:`,
    `     <link rel="stylesheet" href="css/base.css">`,
    `     <link rel="stylesheet" href="css/${c.id}.css">`,
    `  `,
    `   Every value below is a var(--um-*). A theme file decides what those`,
    `   variables hold; this file never decides anything on its own.`,
    `   ========================================================================== */`,
    ``,
  ].join("\n");

  // The quality hooks close the file: a hook overrides the component's own
  // shadow, so it has to come after the component's rules.
  const body = [c.css, ...hooks.map((h) => h.css)].join("\n\n");
  writeFileSync(join(outDir, `${c.id}.css`), `${header}${body}\n`, "utf8");
}

// --- the whole sheet, for a host that wants one file -------------------------

const allHeader = [
  `/* ============================================================================`,
  `   ui-moods · component layer, all in one file`,
  `   ----------------------------------------------------------------------------`,
  `   GENERATED by tools/build-dist.mjs — do not edit.`,
  `  `,
  `   This is the same stylesheet as components/um-components.css. Link it if`,
  `   you want the whole library; link css/base.css and css/<id>.css instead`,
  `   if you want only the components you use.`,
  `   ========================================================================== */`,
  ``,
].join("\n");

writeFileSync(
  join(outDir, "all.css"),
  `${allHeader}${chunks.map((c) => c.css).join("\n\n")}\n`,
  "utf8",
);

// --- report ------------------------------------------------------------------

const total = components.reduce((n, c) => n + c.css.length, 0);
console.log(
  `dist: ${components.length} component files + base.css + all.css ` +
    `(${(total / 1024).toFixed(1)} KB of component CSS)`,
);
