#!/usr/bin/env node
// ui-moods build-apps — render industry app screens from app.json + a mood.
//
// An "app" is an industry reference pack: a set of mobile screens described
// as data (blocks), rendered against one mood's design tokens. The result is
// a folder of self-contained HTML screens.
//
// Usage:
//   ui-moods build-apps <app-id> [--mood <mood-id>] [--out <dir>]
//   ui-moods build-apps --all
//
// Output: apps/<id>/screens/<screen-id>.html  (generated — never hand-edit)

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { renderBlocks } from "./lib/blocks.mjs";
import { MAPPED_GROUPS, SKIP_FIELDS, kebabCase } from "./lib/mapping.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function loadJson(path) {
  return JSON.parse(readFileSync(path, "utf8").replace(/^\uFEFF/, ""));
}

/** Build the CSS custom property block from a tokens file. */
function buildVars(tokens) {
  const lines = [];
  for (const group of MAPPED_GROUPS) {
    const obj = tokens[group];
    if (!obj || typeof obj !== "object") continue;
    for (const [key, value] of Object.entries(obj)) {
      if (SKIP_FIELDS.has(key)) continue;
      if (typeof value !== "string" && typeof value !== "number") continue;
      lines.push(`      --mood-${group}-${kebabCase(key)}: ${value};`);
    }
  }
  return lines.join("\n");
}

/**
 * Assemble one screen.
 * `chrome` provides the persistent app furniture (status bar / app bar / tab
 * bar); a screen may override any of it or supply its own body blocks.
 */
function renderScreen(app, screen, tokens, appCss) {
  const chrome = app.chrome ?? {};
  const scr = screen.chrome ?? {};

  const statusbar = scr.statusbar ?? chrome.statusbar;
  const navbar = scr.navbar ?? chrome.navbar;
  const tabbar = scr.tabbar ?? chrome.tabbar;

  const head = statusbar ? renderBlocks([{ type: "statusbar", ...statusbar }]) : "";
  const bar = navbar
    ? renderBlocks([{ type: "navbar", title: screen.title, ...navbar }])
    : "";
  const body = renderBlocks(screen.blocks ?? []);
  const tabs = tabbar ? renderBlocks([{ type: "tabbar", ...tabbar }]) : "";

  const title = `${app.name} · ${screen.title} — UI Moods App Reference`;

  return `<!DOCTYPE html>
<html lang="zh-CN">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${title}</title>
  <!--
    Generated by ui-moods build-apps — do not hand-edit.
    App: ${app.id} · Screen: ${screen.id}
    Mood: ${tokens.id}@${tokens.version} (${tokens.meta?.name} / ${tokens.meta?.nameZh})
    All visual parameters come from var(--mood-*); see the token block below.
  -->
  <style id="mood-tokens">
    :root {
${buildVars(tokens)}
    }
  </style>
  <style>
${appCss}
  </style>
</head>
<body>
  <div class="app-frame">
    <div class="app-body">
      <div class="app-pad">
${head}
${bar}
${body}
      </div>
    </div>
${tabs}
  </div>
</body>
</html>
`;
}

/**
 * Strip comments and collapse whitespace from the stylesheet so each screen
 * stays a compact, self-contained file. The source of truth remains
 * templates/app/app.css — this only affects the generated copy.
 */
function minifyCss(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{}:;,])\s*/g, "$1")
    .replace(/;}/g, "}")
    .trim();
}

function buildApp(appId, opts = {}) {
  const appDir = join(root, "apps", appId);
  const appPath = join(appDir, "app.json");
  if (!existsSync(appPath)) {
    console.error(`app not found: ${appPath}`);
    return { ok: false, files: [] };
  }
  const app = loadJson(appPath);

  const moodId = opts.mood ?? app.mood;
  const moodPath = join(root, "moods", moodId, "tokens.json");
  if (!existsSync(moodPath)) {
    console.error(`mood not found for app ${appId}: ${moodPath}`);
    return { ok: false, files: [] };
  }
  const tokens = loadJson(moodPath);

  const appCss = minifyCss(
    readFileSync(join(root, "templates", "app", "app.css"), "utf8"),
  );

  const outDir = opts.out ? join(root, opts.out) : join(appDir, "screens");
  mkdirSync(outDir, { recursive: true });

  const files = [];
  for (const screen of app.screens ?? []) {
    const html = renderScreen(app, screen, tokens, appCss);
    const outPath = join(outDir, `${screen.id}.html`);
    writeFileSync(outPath, html, "utf8");
    files.push(outPath);
  }

  // A small index that links every screen of the app.
  const indexRows = (app.screens ?? [])
    .map(
      (s) =>
        `<li><a href="./${s.id}.html">${s.title ?? s.id}</a>` +
        (s.titleZh ? ` <span>${s.titleZh}</span>` : "") +
        (s.note ? ` <em>${s.note}</em>` : "") +
        `</li>`,
    )
    .join("\n");
  const indexHtml = `<!DOCTYPE html>
<html lang="zh-CN">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${app.name} · ${app.nameZh} — UI Moods App Reference</title>
  <style>
    body {
      margin: 0;
      padding: 32px;
      background: var(--mood-colors-bg);
      color: var(--mood-colors-text);
      font-family: var(--mood-typography-family);
      font-size: var(--mood-typography-body-size);
      line-height: 1.7;
    }
    h1 { font-size: var(--mood-typography-display-size); color: var(--mood-colors-text-strong); margin: 0 0 6px; }
    p.lead { color: var(--mood-colors-muted); margin: 0 0 24px; max-width: 640px; }
    ul { list-style: none; padding: 0; margin: 0; display: flex; flex-direction: column; gap: 10px; max-width: 640px; }
    li {
      padding: 14px 18px;
      border: var(--mood-borders-width) var(--mood-borders-style) var(--mood-colors-border);
      border-radius: var(--mood-radii-card);
      background: var(--mood-colors-surface);
      box-shadow: var(--mood-shadows-card);
    }
    a { color: var(--mood-colors-accent); font-weight: 600; text-decoration: none; }
    a:hover { text-decoration: underline; }
    li span { color: var(--mood-colors-muted); margin-left: 6px; }
    li em { display: block; font-style: normal; font-size: var(--mood-typography-label-size); color: var(--mood-colors-muted); margin-top: 4px; }
  </style>
  <style id="mood-tokens">
    :root {
${buildVars(tokens)}
    }
  </style>
</head>
<body>
  <h1>${app.name} · ${app.nameZh}</h1>
  <p class="lead">${app.description ?? ""}</p>
  <ul>
${indexRows}
  </ul>
</body>
</html>
`;
  writeFileSync(join(outDir, "index.html"), indexHtml, "utf8");
  files.push(join(outDir, "index.html"));

  return { ok: true, files, screenCount: (app.screens ?? []).length };
}

/* --------------------------------------------------------------- CLI */

const args = process.argv.slice(2);
const appIds = [];
let moodOverride = null;
let outDir = null;
let all = false;

for (let i = 0; i < args.length; i++) {
  if (args[i] === "--mood") moodOverride = args[++i];
  else if (args[i] === "--out") outDir = args[++i];
  else if (args[i] === "--all") all = true;
  else if (!args[i].startsWith("--")) appIds.push(args[i]);
}

if (!all && appIds.length === 0) {
  console.error("usage: ui-moods build-apps <app-id> [--mood <id>] | --all");
  process.exit(1);
}

const targets = all
  ? loadJson(join(root, "apps.json")).apps.map((a) => a.id)
  : appIds;

let failed = 0;
for (const id of targets) {
  const result = buildApp(id, { mood: moodOverride, out: outDir });
  if (!result.ok) {
    failed++;
    continue;
  }
  console.log(
    `apps/${id}: ${result.screenCount} screens → apps/${id}/screens/ (mood: ${moodOverride ?? loadJson(join(root, "apps", id, "app.json")).mood})`,
  );
}
process.exit(failed ? 1 : 0);
