#!/usr/bin/env node
// build-themes — moods/<id>/tokens.json → themes/<id>.css
//
// One file per mood, each holding nothing but the component library's role
// variables. That is the whole point: the component CSS reads `--um-*`, and
// which values those hold is decided entirely by which theme file is linked.
//
//   <link rel="stylesheet" href="components/um-components.css">
//   <link rel="stylesheet" href="themes/neon.css">
//
// The contract is tokens/roles.json. A role that cannot be resolved is an
// error, not a warning: a component reading a variable nobody defines renders
// wrong on that theme and only that theme.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadContract, resolveTheme, themeCss, themeScopeCss, themeDefaultCss } from "./lib/theme.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contract = loadContract(join(root, "tokens", "roles.json"));
const index = JSON.parse(readFileSync(join(root, "moods.json"), "utf8"));

const outDir = join(root, "themes");
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });

// `--mood <id>` and a bare id both select a subset; no argument means all.
const argv = process.argv.slice(2);
const only = [];
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === "--mood" && argv[i + 1]) only.push(argv[++i]);
  else if (!argv[i].startsWith("--")) only.push(argv[i]);
}
const allIds = index.moods.map((m) => m.id);
const ids = only.length ? only : allIds;
const selected = new Set(ids);

let failed = 0;
const catalogue = [];
const resolved = new Map();

// Every theme is resolved, so `themes/index.json` always describes the whole
// set; only the requested files are written. Building one theme used to
// rewrite the catalogue with that one entry and silently drop the other 31.
for (const id of allIds) {
  const tokensPath = join(root, "moods", id, "tokens.json");
  if (!existsSync(tokensPath)) {
    console.error(`moods/${id}/tokens.json not found`);
    failed++;
    continue;
  }
  const tokens = JSON.parse(readFileSync(tokensPath, "utf8").replace(/^\uFEFF/, ""));
  const { values, missing } = resolveTheme(tokens, contract);
  if (missing.length) {
    console.error(`themes/${id}.css: unresolved roles — ${missing.join(", ")}`);
    failed++;
    continue;
  }
  if (selected.has(id)) {
    writeFileSync(join(outDir, `${id}.css`), themeCss(id, values, contract, tokens.meta), "utf8");
  }
  resolved.set(id, { values, meta: tokens.meta });
  catalogue.push({
    id,
    name: tokens.meta?.name ?? id,
    nameZh: tokens.meta?.nameZh ?? "",
    appearance: tokens.meta?.appearance ?? "light",
    file: `themes/${id}.css`,
    roles: values.size,
  });
}

// The combined sheet.
//
// Every theme on one page, so that switching a mood is a change of an
// attribute rather than a change of a stylesheet. Each theme claims its own
// scope at a specificity one step above `:root`, so the theme that matches
// the attribute wins whatever order the files are in — and the `:root` parts
// of the other thirty-one cannot take it back.
//
// **Every** theme gets a scope, the default one included. A scope is what
// lets a *subtree* wear a mood — the bare `[data-um-theme="x"]` selector is
// there for exactly that — and a default mood that had only a `:root` block
// could be worn by the document and by nothing else.
//
// The default mood also carries a `:root` block, and it is the last thing in
// the sheet. It therefore answers for every case no scope covers: a document
// that names no mood, and a document that names a mood that does not exist.
// A typo in a mood id lands on the default mood instead of on whichever mood
// happened to be linked last.
const defaultId = catalogue.find((t) => t.appearance === "dark")?.id ?? catalogue[0]?.id;
if (defaultId && resolved.size === allIds.length) {
  const parts = catalogue.map((t) => {
    const r = resolved.get(t.id);
    return themeScopeCss(t.id, r.values, contract, r.meta);
  });
  const fallback = resolved.get(defaultId);
  parts.push(themeDefaultCss(defaultId, fallback.values, contract, fallback.meta));
  writeFileSync(
    join(outDir, "all.css"),
    [
      `/* ui-moods · all themes in one sheet`,
      ` * Generated by tools/build-themes.mjs — do not edit.`,
      ` *`,
      ` * Link it once, then name the mood on the document:`,
      ` *   <link rel="stylesheet" href="themes/all.css">`,
      ` *   document.documentElement.setAttribute('data-um-theme', 'night')`,
      ` *`,
      ` * Switching costs no network request, because every mood is already here.`,
      ` * The default mood is ${defaultId}; a document that names none — or names`,
      ` * one that does not exist — gets it.`,
      ` */`,
      "",
      ...parts,
    ].join("\n"),
    "utf8",
  );
}

writeFileSync(
  join(outDir, "index.json"),
  JSON.stringify(
    {
      version: contract.version,
      prefix: contract.prefix,
      default: defaultId ?? null,
      combined: "themes/all.css",
      switcher: "themes/switcher.js",
      themes: catalogue,
    },
    null,
    2,
  ) + "\n",
  "utf8",
);

const written = catalogue.filter((t) => selected.has(t.id)).length;
console.log(
  `themes/: ${written} file(s) written, ${catalogue.length} in the catalogue, ${failed} failed`,
);
process.exit(failed ? 1 : 0);