#!/usr/bin/env node
// build-types — components/<id>/manifest.json  →  types/index.d.ts
//
// The library ships plain CSS, so there is nothing to type at runtime. But a
// consumer still wants to know, without reading the stylesheet, which
// variants exist and what they are called — and a future component wrapper
// needs exactly that list to derive its props.
//
// So the manifests are compiled into a declaration file: the theme ids as a
// union, and one interface per component with its variant, size and prop
// types. It is the same source the CSS and the documentation come from, so
// the three cannot drift.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadManifests } from "./lib/manifest.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const { manifests, problems } = loadManifests(root);
if (problems.length) {
  for (const p of problems) console.error(`types: ${p}`);
  console.log(`types: FAIL (${problems.length} errors)`);
  process.exit(1);
}

const themesIndex = JSON.parse(readFileSync(join(root, "themes", "index.json"), "utf8").replace(/^\uFEFF/, ""));
const themeIds = themesIndex.themes.map((t) => t.id);

/** `button` → `Button` */
const typeName = (id) =>
  id
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const union = (values) => (values.length ? values.map((v) => `"${v}"`).join(" | ") : "never");

const lines = [];

// --- header -----------------------------------------------------------------
lines.push("// ============================================================================");
lines.push("// ui-moods · component types");
lines.push("//");
lines.push("// GENERATED by tools/build-types.mjs from components/<id>/manifest.json — do not edit.");
lines.push("//");
lines.push(`// One component implementation, ${themeIds.length} skins. The type names below`);
lines.push("// are the same ones the CSS uses: a variant is a class, and the class is the");
lines.push("// only thing a consumer has to get right.");
lines.push("// ============================================================================");
lines.push("");

// --- themes -----------------------------------------------------------------
lines.push(`/** Every theme the library ships. */`);
lines.push(`export type ThemeId =`);
lines.push(`  | ${themeIds.map((id) => `"${id}"`).join("\n  | ")};`);
lines.push("");
lines.push(`/** The themes that read as light, and the ones that read as dark. */`);
lines.push(`export interface ThemeCatalogue {`);
lines.push(`  light: ThemeId[];`);
lines.push(`  dark: ThemeId[];`);
lines.push(`}`);
lines.push("");

// --- per component ----------------------------------------------------------
for (const m of manifests) {
  const Name = typeName(m.id);
  const variants = (m.variants ?? []).map((v) => v.id);
  const sizes = (m.sizes ?? []).map((s) => s.id);

  if (variants.length) {
    lines.push(`/** ${m.name}${m.nameZh ? ` · ${m.nameZh}` : ""} — ${m.summary} */`);
    lines.push(`export type ${Name}Variant = ${union(variants)};`);
  }
  if (sizes.length) {
    lines.push(`/** ${m.name} — the sizes it can be rendered at. */`);
    lines.push(`export type ${Name}Size = ${union(sizes)};`);
  }

  lines.push(`export interface ${Name}Props {`);
  lines.push(`  /** The component's own id, so a registry can be keyed by it. */`);
  lines.push(`  id: "${m.id}";`);
  if (variants.length) lines.push(`  variant?: ${Name}Variant;`);
  if (sizes.length) lines.push(`  size?: ${Name}Size;`);
  for (const p of m.props ?? []) {
    if (p.name === "variant" && variants.length) continue;
    if (p.name === "size" && sizes.length) continue;
    let type = "string";
    if (p.type === "boolean") type = "boolean";
    else if (p.type === "number") type = "number";
    else if (p.type === "enum") type = union(p.values ?? []);
    else if (p.type === "string") type = "string";
    lines.push(`  /** ${(p.description ?? p.descriptionZh ?? p.name).replace(/\*\//g, "*\\/")} */`);
    lines.push(`  ${p.name}?: ${type};`);
  }
  lines.push(`}`);
  lines.push("");
}

// --- the registry -----------------------------------------------------------
lines.push(`/** Every component the library ships, keyed by id. */`);
lines.push(`export interface ComponentRegistry {`);
for (const m of manifests) {
  lines.push(`  ${m.id}: ${typeName(m.id)}Props;`);
}
lines.push(`}`);
lines.push("");
lines.push(`/** The catalogue entry for one component. */`);
lines.push(`export interface ComponentCatalogueEntry {`);
lines.push(`  id: string;`);
lines.push(`  name: string;`);
lines.push(`  nameZh: string;`);
lines.push(`  category: "basic" | "form" | "data" | "navigation" | "feedback" | "other";`);
lines.push(`  element: string;`);
lines.push(`  summary: string;`);
lines.push(`  since: string;`);
lines.push(`  file: string;`);
lines.push(`  style: string;`);
lines.push(`  doc: string;`);
lines.push(`  variants: number;`);
lines.push(`  sizes: number;`);
lines.push(`  states: number;`);
lines.push(`  parts: number;`);
lines.push(`  props: number;`);
lines.push(`}`);
lines.push("");
lines.push(`export declare const themes: ThemeCatalogue;`);
lines.push(`export declare const components: ComponentCatalogueEntry[];`);

const outDir = join(root, "types");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "index.d.ts"), lines.join("\n"), "utf8");

console.log(`types: ${manifests.length} component interfaces, ${themeIds.length} theme ids`);
