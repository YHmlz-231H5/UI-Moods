#!/usr/bin/env node
// build-vue — the Vue 3 component package.
//
// The components themselves live in `vue/components/<id>.js`, one hand-written
// wrapper per component. This script does not write those; it writes the two
// files that must never be written by hand:
//
//   vue/components/index.js      — the barrel and the plugin
//   vue/components/index.d.ts    — the declarations
//
// Both are derived from the same manifests the CSS and the documentation come
// from, so the Vue layer cannot drift away from the stylesheet: a component
// that the manifests do not describe has no Vue wrapper in the barrel, and a
// prop the manifests declare has a type in the declaration file.
//
// The package has no build step for its consumers. These files are committed,
// so a Vue project can `import { UMButton } from "ui-moods/vue"` and be done.

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadManifests } from "./lib/manifest.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const { manifests, problems } = loadManifests(root);
if (problems.length) {
  for (const p of problems) console.error(`vue: ${p}`);
  console.log(`vue: FAIL (${problems.length} errors)`);
  process.exit(1);
}

/** `input-number` → `InputNumber` */
const pascal = (id) =>
  id
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

/** `UMInputNumber` → `um-input-number` */
const kebab = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();

const componentName = (id) => `UM${pascal(id)}`;

// --- which wrappers exist ----------------------------------------------------
const wrapperDir = join(root, "vue", "components");
mkdirSync(wrapperDir, { recursive: true });

const wrapperFiles = existsSync(wrapperDir)
  ? readdirSync(wrapperDir)
      .filter((f) => f.endsWith(".js") && f !== "index.js")
      .sort()
  : [];

const wrapped = wrapperFiles.map((f) => f.replace(/\.js$/, ""));
const byId = new Map(manifests.map((m) => [m.id, m]));

const missing = [];
for (const m of manifests) {
  if (!wrapped.includes(m.id)) missing.push(m.id);
}
const orphans = wrapped.filter((id) => !byId.has(id));

const entries = wrapped
  .map((id) => {
    const m = byId.get(id);
    return { id, name: componentName(id), manifest: m };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

// --- the barrel --------------------------------------------------------------
const lines = [];
lines.push("// ============================================================================");
lines.push("// ui-moods · Vue 3 components");
lines.push("//");
lines.push("// GENERATED by tools/build-vue.mjs — do not edit.");
lines.push("//");
lines.push(`// ${entries.length} components, one wrapper each, all of them plain CSS with a`);
lines.push("// `um-` class underneath. Nothing here reimplements a component: the markup");
lines.push("// is the same markup the documentation shows, and the stylesheet still");
lines.push("// decides what it looks like in whichever mood is in force.");
lines.push("// ============================================================================");
lines.push("");
for (const e of entries) {
  lines.push(`import { ${e.name} } from "./${e.id}.js";`);
}
lines.push("");
lines.push("/** Every component the package ships, keyed by its name. */");
lines.push("export const components = {");
for (const e of entries) {
  lines.push(`  ${e.name},`);
}
lines.push("};");
lines.push("");
lines.push("export {");
for (const e of entries) {
  lines.push(`  ${e.name},`);
}
lines.push("};");
lines.push("");
lines.push("/**");
lines.push(" * Install the whole library into a Vue app.");
lines.push(" *");
lines.push(" *   import { createApp } from \"vue\";");
lines.push(" *   import UM from \"ui-moods/vue\";");
lines.push(" *   createApp(App).use(UM).mount(\"#app\");");
lines.push(" *");
lines.push(" * Every component is registered twice: as `UMButton` and as `um-button`,");
lines.push(" * so a template can use whichever reads better.");
lines.push(" */");
lines.push("export function install(app) {");
lines.push("  for (const [name, component] of Object.entries(components)) {");
lines.push("    app.component(name, component);");
lines.push("    app.component(kebabCase(name), component);");
lines.push("  }");
lines.push("  return app;");
lines.push("}");
lines.push("");
lines.push("/** `UMInputNumber` → `um-input-number` */");
lines.push("export function kebabCase(name) {");
lines.push("  return name");
lines.push("    .replace(/([a-z0-9])([A-Z])/g, \"$1-$2\")");
lines.push("    .replace(/([A-Z])([A-Z][a-z])/g, \"$1-$2\")");
lines.push("    .toLowerCase();");
lines.push("}");
lines.push("");
lines.push("export default { install, components };");
lines.push("");

writeFileSync(join(wrapperDir, "index.js"), lines.join("\n"), "utf8");

// --- the declarations --------------------------------------------------------
const dts = [];
dts.push("// ============================================================================");
dts.push("// ui-moods · Vue 3 components — types");
dts.push("//");
dts.push("// GENERATED by tools/build-vue.mjs from components/<id>/manifest.json — do not edit.");
dts.push("// ============================================================================");
dts.push("");
dts.push('import type { DefineComponent } from "vue";');
dts.push("");

for (const e of entries) {
  const m = e.manifest;
  const props = m.props ?? [];
  dts.push(`/** ${m.name}${m.nameZh ? ` · ${m.nameZh}` : ""} — ${m.summary} */`);
  dts.push(`export interface ${e.name}Props {`);
  for (const p of props) {
    const name = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(p.name) ? p.name : p.name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
    let type = "string";
    if (p.type === "boolean") type = "boolean";
    else if (p.type === "number") type = "number";
    else if (p.type === "enum") type = (p.values ?? []).map((v) => `"${v}"`).join(" | ") || "string";
    dts.push(`  /** ${(p.description ?? p.descriptionZh ?? p.name).replace(/\*\//g, "*\\/")} */`);
    dts.push(`  ${name}?: ${type};`);
  }
  dts.push("}");
  dts.push("");
  dts.push(`export declare const ${e.name}: DefineComponent<${e.name}Props>;`);
  dts.push("");
}

dts.push("/** Every component the package ships, keyed by its name. */");
dts.push("export declare const components: Record<string, DefineComponent<any>>;");
dts.push("");
dts.push("/** Install the whole library into a Vue app. */");
dts.push("export declare function install(app: any): any;");
dts.push("");
dts.push("/** `UMInputNumber` → `um-input-number` */");
dts.push("export declare function kebabCase(name: string): string;");
dts.push("");
dts.push("declare const _default: { install: typeof install; components: typeof components };");
dts.push("export default _default;");
dts.push("");

writeFileSync(join(wrapperDir, "index.d.ts"), dts.join("\n"), "utf8");

// --- report ------------------------------------------------------------------
console.log(
  `vue: ${entries.length} components, ${wrapperFiles.length} wrapper files` +
    (missing.length ? `, ${missing.length} still unwrapped` : ""),
);
if (missing.length) console.log(`vue: no wrapper yet for ${missing.join(", ")}`);
if (orphans.length) {
  console.log(`vue: FAIL — wrapper without a manifest: ${orphans.join(", ")}`);
  process.exit(1);
}
